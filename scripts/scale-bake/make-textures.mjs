/**
 * The pictures Scale's models read from. Two, both generated:
 *
 *   earth.png      where the land is — Natural Earth's coastline, the same one
 *                  the site's maps use, as an equirectangular mask
 *   buckyball.glsl the sixty vertices of a truncated icosahedron
 *
 *   node scripts/scale-bake/make-textures.mjs
 */
import { Resvg } from '@resvg/resvg-js'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { register } from 'node:module'
import sharp from 'sharp'
register('../resolve-ts.mjs', import.meta.url)

const here = path.dirname(fileURLToPath(import.meta.url))
const { LAND_PATH, MAP_W, MAP_H } = await import('../../src/data/world.ts')

fs.mkdirSync(path.join(here, 'textures'), { recursive: true })
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${MAP_W} ${MAP_H}"><rect width="${MAP_W}" height="${MAP_H}" fill="#000"/><path d="${LAND_PATH}" fill="#fff"/></svg>`
const png = new Resvg(svg, { fitTo: { mode: 'width', value: 2048 }, font: { loadSystemFonts: false } }).render().asPng()
// Red is the coast itself; green is the same thing blurred, which is how far
// out to sea or inland a point is — shallows, and the colour of a continent's
// interior — without a second lookup.
const sharpMask = await sharp(png).greyscale().raw().toBuffer({ resolveWithObject: true })
const soft = await sharp(png).greyscale().blur(14).raw().toBuffer()
const { width, height } = sharpMask.info
const out = Buffer.alloc(width * height * 3)
for (let i = 0; i < width * height; i++) { out[i * 3] = sharpMask.data[i]; out[i * 3 + 1] = soft[i]; out[i * 3 + 2] = 0 }
await sharp(out, { raw: { width, height, channels: 3 } }).png({ compressionLevel: 9 }).toFile(path.join(here, 'textures', 'earth.png'))
console.log(`earth.png ${width}x${height}`)

/* ---- C60 ---------------------------------------------------------------- */
const phi = (1 + Math.sqrt(5)) / 2
const seeds = [[0, 1, 3 * phi], [1, 2 + phi, 2 * phi], [phi, 2, 2 * phi + 1]]
const verts = []
for (const s of seeds) for (let rotn = 0; rotn < 3; rotn++) {
  const v = [s[rotn % 3], s[(rotn + 1) % 3], s[(rotn + 2) % 3]]
  for (let m = 0; m < 8; m++) {
    const w = v.map((x, k) => ((m >> k) & 1 ? -x : x))
    if (!verts.some((u) => u.every((x, k) => Math.abs(x - w[k]) < 1e-9))) verts.push(w)
  }
}
if (verts.length !== 60) throw new Error('expected sixty vertices, got ' + verts.length)
const R = Math.hypot(...verts[0])
const f = (x) => { const s = (x / R).toFixed(5); return s.includes('.') ? s : s + '.0' }
fs.writeFileSync(path.join(here, 'textures', 'buckyball.glsl'),
  `// GENERATED by make-textures.mjs: the sixty carbons of C60, on the unit sphere.\n// Bonded neighbours are ${(2 / R).toFixed(5)} apart.\nconst float BOND = ${(2 / R).toFixed(5)};\nconst vec3 C60[60] = vec3[](\n` +
  verts.map((v) => `  vec3(${v.map(f).join(', ')})`).join(',\n') + ');\n')
console.log('buckyball.glsl 60 vertices')
