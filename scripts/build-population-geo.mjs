/**
 * Generates src/data/population-geo.ts — the real political boundary of every
 * country on Earth, for Every Second, Somewhere's map.
 *
 *   node scripts/build-population-geo.mjs
 *
 * Same source and the same reasoning as scripts/build-world-data.mjs: a real
 * public dataset, fetched and projected once at author time rather than
 * shipped as a runtime dependency or fetched from a live tile server. The
 * first version of this page drew its own hand-placed continent blobs
 * instead of doing this — twenty-odd guessed points per landmass — and it
 * looked exactly like what it was. This is the real Natural Earth country
 * geometry, the same family of data neal.fun's own Baby Map draws.
 *
 * Source: world-atlas countries-110m (Natural Earth 1:110m admin-0, public
 * domain), via jsdelivr.
 */
import { writeFileSync } from 'fs'

const MAP_W = 360
const MAP_H = 180

/* ---- topojson decoding — identical approach to build-world-data.mjs ----- */

function decodeArcs(topo) {
  const [sx, sy] = topo.transform.scale
  const [tx, ty] = topo.transform.translate
  return topo.arcs.map((arc) => {
    let x = 0
    let y = 0
    return arc.map(([dx, dy]) => {
      x += dx
      y += dy
      return [x * sx + tx, y * sy + ty]
    })
  })
}

const project = ([lon, lat]) => [((lon + 180) / 360) * MAP_W, ((90 - lat) / 180) * MAP_H]

function ringPoints(ring, arcs) {
  const pts = []
  for (const idx of ring) {
    const arc = idx >= 0 ? arcs[idx] : [...arcs[~idx]].reverse()
    for (const p of pts.length ? arc.slice(1) : arc) pts.push(p)
  }
  return pts
}

/** Project a ring to an SVG path, breaking wherever it crosses the
 *  antimeridian — see build-world-data.mjs's own note on why. */
function pointsToPath(pts) {
  const projected = pts.map(project)
  let d = ''
  let prevX = null
  for (const [x, y] of projected) {
    const wrapped = prevX !== null && Math.abs(x - prevX) > MAP_W / 2
    d += `${d === '' || wrapped ? 'M' : 'L'}${x.toFixed(2)} ${y.toFixed(2)}`
    prevX = x
  }
  return d + 'Z'
}

function ringArea(pts) {
  // Real signed area in equirectangular space — enough to tell a country's
  // main landmass from a scattering of tiny islands, which is all this is
  // used for (picking where a label anchors).
  let a = 0
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i]
    const [x2, y2] = pts[(i + 1) % pts.length]
    a += x1 * y2 - x2 * y1
  }
  return a / 2
}

function featurePath(geom, arcs) {
  const polys = geom.type === 'MultiPolygon' ? geom.arcs : [geom.arcs]
  let d = ''
  let biggest = { area: 0, pts: null }
  for (const poly of polys) {
    const outer = ringPoints(poly[0], arcs)
    d += pointsToPath(outer)
    for (const ring of poly.slice(1)) d += pointsToPath(ringPoints(ring, arcs))
    const area = Math.abs(ringArea(outer))
    if (area > biggest.area) biggest = { area, pts: outer }
  }
  // Centroid of the largest ring's projected bounding box — a real, if rough,
  // point inside the country's main landmass, used only to anchor a label.
  const proj = biggest.pts.map(project)
  const xs = proj.map((p) => p[0])
  const ys = proj.map((p) => p[1])
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2
  const cy = (Math.min(...ys) + Math.max(...ys)) / 2
  return { path: d, cx, cy }
}

const topo = await (await fetch('https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json')).json()
const arcs = decodeArcs(topo)
const objects = topo.objects.countries.geometries

const shapes = objects
  .filter((g) => g.properties?.name && g.arcs)
  .map((g) => {
    const { path, cx, cy } = featurePath(g, arcs)
    return { name: g.properties.name, path, cx: Number(cx.toFixed(2)), cy: Number(cy.toFixed(2)) }
  })

const file = `/**
 * GENERATED by scripts/build-population-geo.mjs — do not edit by hand.
 *
 * Real political boundaries for ${shapes.length} countries and territories —
 * Natural Earth 1:110m admin-0 via world-atlas, public domain — projected
 * equirectangular into a ${MAP_W}x${MAP_H} viewBox. \`cx\`/\`cy\` is a rough
 * centroid of each country's largest ring, real enough to anchor a label,
 * not claimed as more precise than that.
 */

export const MAP_W = ${MAP_W}
export const MAP_H = ${MAP_H}

export type CountryShape = { name: string; path: string; cx: number; cy: number }

export const COUNTRY_SHAPES: CountryShape[] = ${JSON.stringify(shapes)}
`

writeFileSync('src/data/population-geo.ts', file)
console.log(`wrote src/data/population-geo.ts — ${shapes.length} real country shapes, ${(file.length / 1024).toFixed(0)} KB`)
